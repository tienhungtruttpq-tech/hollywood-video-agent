    picks=[]
    for p in pool:
        if len(picks)==2:break
        base=re.sub(r'\s*\((crop|cropped|square)\)\s*','',p['title'],flags=re.I)
        if any(base==re.sub(r'\s*\((crop|cropped|square)\)\s*','',q['title'],flags=re.I) for q in picks):continue
        picks.append(p)
    return f'{i:02d}_{era}',picks

