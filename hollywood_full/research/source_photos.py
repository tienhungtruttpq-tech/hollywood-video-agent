def clean(value):return html.unescape(re.sub('<[^>]+>','',value or '')).strip()
def simple(page,year):
    if 'imageinfo' not in page:return None
    ii=page['imageinfo'][0];md=ii.get('extmetadata',{})
    v=lambda k:clean(md.get(k,{}).get('value',''))
    return {'pageid':page['pageid'],'title':page['title'],'url':ii['url'].split('?')[0],
            'source':ii['descriptionurl'],'width':ii['width'],'height':ii['height'],
            'year':year,'date':v('DateTimeOriginal'),'description':v('ImageDescription'),
            'artist':v('Artist'),'license':v('LicenseShortName'),'license_url':v('LicenseUrl'),
            'credit':v('Credit')}

def get_category(name,year):
    catname='Robert Downey, Jr.' if name=='Robert Downey Jr.' else name
    file=ROOT/'research'/('pool_'+name.replace(' ','_')+'_'+str(year)+'.json')
    if file.exists():return json.loads(file.read_text())
    p={'action':'query','format':'json','generator':'categorymembers','gcmtitle':f'Category:{catname} in {year}',
       'gcmtype':'file','gcmlimit':'50','prop':'imageinfo','iiprop':'url|size|extmetadata'}
    r=requests.get(API,params=p,headers=HEAD,timeout=45);r.raise_for_status();d=r.json()
    pages=d.get('query',{}).get('pages',{})
    out=[simple(x,year) for x in pages.values()];out=[x for x in out if x]
    file.write_text(json.dumps(out,ensure_ascii=False,indent=2));return out

def score(p,name):
    title=p['title'].lower();desc=p['description'].lower();both=title+' '+desc
    if not re.search(r'\.(jpe?g|png)$',title):return -999
    if not any(s in p['license'] for s in ['CC BY','Public domain','CC0']):return -999
    if any(s in both for s in ['wax figure','waxwork','sculpture','caricature','drawing','signature','autograph','statuette','generated by ai','ai-generated','painting','oil on canvas']):return -999
    # Do not use material dated after the current date.
    dat=re.search(r'\b(2026)-(\d{2})-(\d{2})',p['date'])
    if dat and dat.group(0)>'2026-09-05':return -999
    if min(p['width'],p['height'])<180:return -999
    s=0.;aspect=p['width']/p['height']
    s+=7 if .58<aspect<.95 else (4 if .95<=aspect<1.1 else -1)
    s+=min(5,math.log2(max(min(p['width'],p['height']),1)/200)*2)
    n=name.lower().replace(' jr.','').replace('.','').replace(',','')
    t=title.replace('.','').replace(',','')
    if t.startswith('file:'+n):s+=5
    if 'cropped' in title or '(crop)' in title:s+=5
    if 'portrait' in title or 'headshot' in title:s+=3
    if ' and ' in title or ' & ' in title or ' with ' in title:s-=7
    if 'group' in both:s-=4
    if any(a in p['artist'] for a in ['Harald Krichel','Georges Biard','Gage Skidmore','Alan Light','Raph_PH']):s+=2
    if str(p['year']) in p['date']:s+=1
    if aspect>1.65:s-=3
    return s

